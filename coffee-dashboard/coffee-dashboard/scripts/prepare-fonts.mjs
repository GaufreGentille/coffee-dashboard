import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { mkdir, readFile, writeFile, copyFile, rm } from 'node:fs/promises'

const require = createRequire(import.meta.url)
const publicDir = new URL('../public/', import.meta.url)
const fontsDir = new URL('../public/fonts/', import.meta.url)

const families = [
  {
    packageName: '@fontsource/dm-sans',
    target: 'dm-sans',
    stylesheets: ['400.css', '500.css', '600.css', '700.css'],
  },
  {
    packageName: '@fontsource/bodoni-moda',
    target: 'bodoni-moda',
    stylesheets: ['700.css', '800.css', '700-italic.css', '800-italic.css'],
  },
]

await rm(fontsDir, { recursive: true, force: true })
await mkdir(fontsDir, { recursive: true })

const output = [
  '/* Generated by scripts/prepare-fonts.mjs. Do not edit by hand. */',
  '/* Fonts are served locally by Kissa Soko. No browser request is sent to Google Fonts. */',
  '',
]

for (const family of families) {
  const packageRoot = dirname(require.resolve(`${family.packageName}/package.json`))
  const targetDir = new URL(`../public/fonts/${family.target}/`, import.meta.url)
  await mkdir(targetDir, { recursive: true })

  for (const stylesheet of family.stylesheets) {
    const cssPath = join(packageRoot, stylesheet)
    let css = await readFile(cssPath, 'utf8')

    const fontFiles = [...css.matchAll(/url\(\.\/files\/([^)]+)\)/g)].map(match => match[1])
    for (const fontFile of new Set(fontFiles)) {
      await copyFile(
        join(packageRoot, 'files', fontFile),
        new URL(`../public/fonts/${family.target}/${fontFile}`, import.meta.url),
      )
    }

    css = css.replaceAll('url(./files/', `url(/fonts/${family.target}/`)
    output.push(`/* ${family.packageName} · ${stylesheet} */`, css.trim(), '')
  }
}

await writeFile(new URL('../public/fonts.css', import.meta.url), output.join('\n'), 'utf8')
console.log('✓ Local fonts prepared in public/fonts and public/fonts.css')
